-- 1. ROLES
CREATE TABLE ROLES (
    role_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR2(50) NOT NULL UNIQUE,
    description VARCHAR2(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. USERS
CREATE TABLE USERS (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id NUMBER NOT NULL,
    email VARCHAR2(255) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    full_name VARCHAR2(255) NOT NULL,
    phone VARCHAR2(50) NOT NULL,
    status VARCHAR2(30) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'BLOCKED', 'PENDING_VERIFICATION')),
    last_login TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES ROLES(role_id)
);

-- 3. DONOR_PROFILES
CREATE TABLE DONOR_PROFILES (
    donor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL UNIQUE,
    blood_group VARCHAR2(10) NOT NULL,
    gender VARCHAR2(20) NOT NULL CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    date_of_birth DATE NOT NULL,
    address VARCHAR2(500) NOT NULL,
    district VARCHAR2(100) NOT NULL,
    city VARCHAR2(100) NOT NULL,
    emergency_contact VARCHAR2(50) NOT NULL,
    last_donation_date DATE,
    total_donations NUMBER DEFAULT 0 NOT NULL,
    verification_status VARCHAR2(30) DEFAULT 'PENDING' CHECK (verification_status IN ('VERIFIED', 'PENDING', 'REJECTED')),
    allow_shortage_alerts NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_donor_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE
);

-- 4. PATIENT_PROFILES
CREATE TABLE PATIENT_PROFILES (
    patient_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL UNIQUE,
    gender VARCHAR2(20) NOT NULL CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    date_of_birth DATE NOT NULL,
    address VARCHAR2(500) NOT NULL,
    district VARCHAR2(100),
    city VARCHAR2(100),
    emergency_contact VARCHAR2(50) NOT NULL,
    total_requests NUMBER DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_patient_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE
);

-- 5. HOSPITALS
CREATE TABLE HOSPITALS (
    hospital_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL UNIQUE,
    hospital_name VARCHAR2(255) NOT NULL,
    hospital_email VARCHAR2(255) NOT NULL UNIQUE,
    phone VARCHAR2(50) NOT NULL,
    registration_number VARCHAR2(100) NOT NULL UNIQUE,
    address VARCHAR2(500) NOT NULL,
    district VARCHAR2(100) NOT NULL,
    city VARCHAR2(100) NOT NULL,
    contact_person VARCHAR2(255) NOT NULL,
    approval_status VARCHAR2(30) DEFAULT 'PENDING' CHECK (approval_status IN ('PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED')),
    rejection_reason VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_hospitals_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE
);

-- 6. HOSPITAL_DOCUMENTS
CREATE TABLE HOSPITAL_DOCUMENTS (
    document_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id NUMBER NOT NULL,
    document_type VARCHAR2(100) NOT NULL,
    file_path VARCHAR2(500) NOT NULL,
    original_name VARCHAR2(255) NOT NULL,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_hosp_docs_hosp FOREIGN KEY (hospital_id) REFERENCES HOSPITALS(hospital_id) ON DELETE CASCADE
);

-- 7. BLOOD_GROUPS
CREATE TABLE BLOOD_GROUPS (
    group_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name VARCHAR2(10) NOT NULL UNIQUE,
    can_donate_to VARCHAR2(100) NOT NULL,
    can_receive_from VARCHAR2(100) NOT NULL,
    description VARCHAR2(255)
);

-- 8. BLOOD_UNITS (Unit-Level Inventory Management)
CREATE TABLE BLOOD_UNITS (
    unit_id VARCHAR2(50) PRIMARY KEY, -- e.g. 'UNIT-2026-A109'
    hospital_id NUMBER NOT NULL,
    blood_group VARCHAR2(10) NOT NULL,
    collection_date DATE NOT NULL,
    expiry_date DATE NOT NULL,
    donation_reference VARCHAR2(100),
    storage_status VARCHAR2(100) DEFAULT 'Cold Room Section A',
    status VARCHAR2(30) DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE', 'RESERVED', 'ASSIGNED', 'EXPIRED', 'DISCARDED')),
    discard_reason VARCHAR2(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_blood_units_hosp FOREIGN KEY (hospital_id) REFERENCES HOSPITALS(hospital_id)
);

-- 9. BLOOD_REQUESTS
CREATE TABLE BLOOD_REQUESTS (
    request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id NUMBER NOT NULL,
    hospital_id NUMBER NOT NULL,
    blood_group VARCHAR2(10) NOT NULL,
    required_units NUMBER NOT NULL CHECK (required_units > 0),
    required_date DATE NOT NULL,
    priority VARCHAR2(20) DEFAULT 'NORMAL' CHECK (priority IN ('NORMAL', 'EMERGENCY')),
    patient_name VARCHAR2(255) NOT NULL,
    patient_age NUMBER NOT NULL,
    treatment_location VARCHAR2(255) NOT NULL,
    doctor_name VARCHAR2(255) NOT NULL,
    doctor_contact VARCHAR2(100),
    additional_notes VARCHAR2(1000),
    service_charge NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    status VARCHAR2(30) DEFAULT 'SUBMITTED' CHECK (
        status IN ('SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'PARTIALLY_FULFILLED', 'BLOOD_ASSIGNED', 'READY_FOR_COLLECTION', 'COMPLETED', 'REJECTED', 'CANCELLED')
    ),
    rejection_reason VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_requests_patient FOREIGN KEY (patient_id) REFERENCES PATIENT_PROFILES(patient_id),
    CONSTRAINT fk_requests_hospital FOREIGN KEY (hospital_id) REFERENCES HOSPITALS(hospital_id)
);

-- 10. REQUEST_DOCUMENTS
CREATE TABLE REQUEST_DOCUMENTS (
    document_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id NUMBER NOT NULL,
    document_type VARCHAR2(100) NOT NULL,
    file_path VARCHAR2(500) NOT NULL,
    original_name VARCHAR2(255) NOT NULL,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_req_docs_request FOREIGN KEY (request_id) REFERENCES BLOOD_REQUESTS(request_id) ON DELETE CASCADE
);

-- 11. REQUEST_STATUS_HISTORY
CREATE TABLE REQUEST_STATUS_HISTORY (
    history_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id NUMBER NOT NULL,
    status VARCHAR2(30) NOT NULL,
    comments VARCHAR2(500),
    changed_by_user_id NUMBER NOT NULL,
    changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_hist_request FOREIGN KEY (request_id) REFERENCES BLOOD_REQUESTS(request_id) ON DELETE CASCADE,
    CONSTRAINT fk_hist_user FOREIGN KEY (changed_by_user_id) REFERENCES USERS(user_id)
);

-- 12. DONATION_APPOINTMENTS
CREATE TABLE DONATION_APPOINTMENTS (
    appointment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id NUMBER NOT NULL,
    hospital_id NUMBER NOT NULL,
    appointment_date DATE NOT NULL,
    time_slot VARCHAR2(50) NOT NULL,
    status VARCHAR2(30) DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
    cancellation_reason VARCHAR2(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_appt_donor FOREIGN KEY (donor_id) REFERENCES DONOR_PROFILES(donor_id),
    CONSTRAINT fk_appt_hosp FOREIGN KEY (hospital_id) REFERENCES HOSPITALS(hospital_id)
);

-- 13. DONATION_RECORDS
CREATE TABLE DONATION_RECORDS (
    record_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id NUMBER,
    donor_id NUMBER NOT NULL,
    hospital_id NUMBER NOT NULL,
    blood_group VARCHAR2(10) NOT NULL,
    quantity_ml NUMBER DEFAULT 450 NOT NULL,
    hemoglobin_level NUMBER(4, 1),
    blood_pressure VARCHAR2(30),
    pulse_rate NUMBER,
    screening_status VARCHAR2(30) DEFAULT 'PASSED' CHECK (screening_status IN ('PASSED', 'DEFERRED', 'REJECTED')),
    processing_status VARCHAR2(30) DEFAULT 'TESTED_AND_STORED' CHECK (processing_status IN ('IN_TESTING', 'TESTED_AND_STORED', 'DISCARDED')),
    unit_id VARCHAR2(50),
    donation_date DATE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_rec_donor FOREIGN KEY (donor_id) REFERENCES DONOR_PROFILES(donor_id),
    CONSTRAINT fk_rec_hosp FOREIGN KEY (hospital_id) REFERENCES HOSPITALS(hospital_id)
);

-- 14. DONATION_CAMPS
CREATE TABLE DONATION_CAMPS (
    camp_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id NUMBER NOT NULL,
    camp_name VARCHAR2(255) NOT NULL,
    location VARCHAR2(500) NOT NULL,
    district VARCHAR2(100) NOT NULL,
    city VARCHAR2(100) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    start_time VARCHAR2(20) NOT NULL,
    end_time VARCHAR2(20) NOT NULL,
    target_units NUMBER DEFAULT 100,
    collected_units NUMBER DEFAULT 0,
    status VARCHAR2(30) DEFAULT 'UPCOMING' CHECK (status IN ('UPCOMING', 'ACTIVE', 'COMPLETED', 'CANCELLED')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_camps_hosp FOREIGN KEY (hospital_id) REFERENCES HOSPITALS(hospital_id)
);

-- 15. NOTIFICATIONS
CREATE TABLE NOTIFICATIONS (
    notification_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    title VARCHAR2(255) NOT NULL,
    message VARCHAR2(1000) NOT NULL,
    notification_type VARCHAR2(30) DEFAULT 'INFORMATION' CHECK (notification_type IN ('INFORMATION', 'SUCCESS', 'WARNING', 'EMERGENCY')),
    is_read NUMBER(1) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_notif_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE
);

-- 16. SUPPORT_TICKETS
CREATE TABLE SUPPORT_TICKETS (
    ticket_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER,
    name VARCHAR2(255) NOT NULL,
    email VARCHAR2(255) NOT NULL,
    subject VARCHAR2(255) NOT NULL,
    message VARCHAR2(2000) NOT NULL,
    status VARCHAR2(30) DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED')),
    response VARCHAR2(2000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 17. SERVICE_CHARGES (Transparent administrative & testing charge configuration)
CREATE TABLE SERVICE_CHARGES (
    charge_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charge_name VARCHAR2(100) NOT NULL,
    amount NUMBER(10, 2) NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    description VARCHAR2(255),
    updated_by_user_id NUMBER,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 18. SYSTEM_SETTINGS
CREATE TABLE SYSTEM_SETTINGS (
    setting_key VARCHAR2(100) PRIMARY KEY,
    setting_value VARCHAR2(1000) NOT NULL,
    description VARCHAR2(255),
    updated_by_user_id NUMBER,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 19. AUDIT_LOGS
CREATE TABLE AUDIT_LOGS (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER,
    user_email VARCHAR2(255),
    action VARCHAR2(100) NOT NULL,
    entity_name VARCHAR2(100),
    entity_id VARCHAR2(100),
    ip_address VARCHAR2(50),
    details VARCHAR2(2000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

