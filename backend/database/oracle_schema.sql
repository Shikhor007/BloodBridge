CREATE INDEX idx_users_role ON USERS(role_id);
CREATE INDEX idx_blood_units_hosp ON BLOOD_UNITS(hospital_id);
CREATE INDEX idx_blood_units_status ON BLOOD_UNITS(status, blood_group);
CREATE INDEX idx_requests_patient ON BLOOD_REQUESTS(patient_id);
CREATE INDEX idx_requests_hospital ON BLOOD_REQUESTS(hospital_id);
CREATE INDEX idx_requests_status ON BLOOD_REQUESTS(status);
CREATE INDEX idx_appointments_donor ON DONATION_APPOINTMENTS(donor_id);
CREATE INDEX idx_appointments_hosp ON DONATION_APPOINTMENTS(hospital_id);
CREATE INDEX idx_notifications_user ON NOTIFICATIONS(user_id, is_read);
CREATE INDEX idx_audit_created ON AUDIT_LOGS(created_at);
